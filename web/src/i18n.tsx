const CATALOGS: Record<Locale, Messages> = { en: EN, zh: ZH, ja: JA };

export interface I18nValue {
  locale: Locale;
  preference: LocalePreference;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

export function normalizeLocale(value: string | null | undefined, fallback: Locale = "en"): Locale {
  const raw = (value ?? "").trim().toLowerCase().replace("_", "-");
  if (raw.startsWith("zh")) return "zh";
  if (raw.startsWith("ja")) return "ja";
  if (raw.startsWith("en")) return "en";
  return fallback;
}

export function detectBrowserLocale(): Locale {
  if (typeof navigator === "undefined") return "en";
  for (const lang of navigator.languages ?? [navigator.language]) {
    const normalized = normalizeLocale(lang, "en");
    if (SUPPORTED_LOCALES.includes(normalized)) return normalized;
  }
  return "en";
}

export function resolveLocale(preference: LocalePreference): Locale {
  if (preference === "auto") {
    if (typeof window !== "undefined") {
      const params = new URLSearchParams(window.location.search);
      const langParam = params.get("lang") || params.get("locale");
      if (langParam) {
        const normalized = normalizeLocale(langParam, "en");
        if (normalized && SUPPORTED_LOCALES.includes(normalized)) {
          return normalized;
        }
      }
    }
    return detectBrowserLocale();
  }
  return preference;
}

export function createI18n(preference: LocalePreference): I18nValue {
  const locale = resolveLocale(preference);
  return {
    locale,
    preference,
    t: (key, vars) => {
      const template = CATALOGS[locale][key] ?? CATALOGS.en[key] ?? key;
      return interpolate(template, vars);
    },
  };
}

const I18nContext = createContext<I18nValue>(createI18n("auto"));

export function I18nProvider({
  preference,
  children,
}: {
  preference: LocalePreference;
  children: ReactNode;
}): JSX.Element {
  const value = useMemo(() => createI18n(preference), [preference]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}

export function languageName(value: LocalePreference): string {
  switch (value) {
    case "zh":
      return "中文";
    case "ja":
      return "日本語";
    case "en":
      return "English";
    default:
      return "Auto";
  }
}
